## 4. Le script d'appel

### Ouverture — 10 secondes, on demande la permission
> « Bonjour [Prénom], Basile Ramé de rAIme. Je vous prends 30 secondes, vous me dites si c'est hors sujet — ça vous va ? »

*(Attendre le oui. Toujours.)*

### La question qui qualifie — le cœur de l'appel
> « On travaille avec des dirigeants à qui on propose de l'IA ou de l'automatisation. Ma question est simple : **est-ce qu'on vous a déjà fait une proposition dans ce domaine — et avez-vous pu vérifier qu'elle était au bon niveau ?** »

**Trois réponses possibles :**
- *« Oui, on a un devis »* → **jackpot**, enchaîner sur l'histoire.
- *« Non, pas encore »* → basculer sur la **formation** : « c'est le bon moment de vous équiper pour juger, avant qu'on vous sollicite. »
- *« Ça ne nous intéresse pas »* → « Compris. Par curiosité : vous avez déjà tranché sur l'IA, ou c'est un sujet que vous repoussez ? » *(relance souvent la conversation)*

### L'histoire — 30 secondes, on illustre au lieu de vendre
> « Un exemple concret. Une entreprise voulait classer 30 000 e-mails par mois. Le prestataire proposait une architecture haut de gamme. On a testé une version plus simple : **résultat quasi identique, pour une fraction du coût**. La question n'était pas "quel modèle est le plus puissant" mais "est-ce que la différence vaut le surcoût". **Personne côté client ne savait y répondre.** C'est exactement notre métier. »

### La proposition de valeur — une phrase
> « Nous ne vendons aucune techno et ne touchons **aucune commission** de prestataire. On est **de votre côté**, on challenge ce qu'on vous propose, et vous décidez. »

### Le closing — proposer UNE seule chose
> « Ce que je vous propose : **30 minutes**. Vous m'envoyez la proposition que vous avez reçue, je vous dis ce que j'en pense, gratuitement. Si ça vous apporte quelque chose, on parle de la suite. **Jeudi 14h ou vendredi 10h ?** »

*(Sans devis en main : « Une demi-journée de formation pour vos équipes, finançable. Je vous envoie le programme ? »)*

