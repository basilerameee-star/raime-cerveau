## 6. Traitement des objections

| Objection | Réponse |
|---|---|
| **« On a déjà un prestataire »** | « Parfait, c'est même le bon moment. Notre rôle n'est pas de le remplacer, c'est de vérifier que ce qu'il vous livre est au juste niveau. S'il est bon, vous le saurez — et vous serez rassuré. » |
| **« C'est cher »** | « Comparons : un audit coûte une fraction de ce que coûte une mauvaise décision sur 3 ans. Dans l'exemple que je vous ai donné, l'écart annuel dépassait 9 000 €. » |
| **« On n'a pas le temps »** | « C'est précisément pour ça. Vous n'avez pas le temps de devenir expert du sujet — nous le sommes déjà. » |
| **« Notre DSI s'en occupe »** | « Excellent. Notre travail est de lui donner des arguments chiffrés face aux fournisseurs. Les meilleures DSI nous appellent pour ça. » |
| **« On verra plus tard »** | « Quand ? Parce qu'après signature, la marge de négociation disparaît. C'est **avant** que tout se joue. » |
| **« Vous êtes un intermédiaire de plus »** | « Un intermédiaire touche une commission. Nous, jamais. C'est ce qui rend notre avis utilisable. » |
| **« On peut le faire avec ChatGPT »** | « Vous pouvez lui poser les questions. Mais il ne testera pas sur vos données, ne chiffrera pas votre coût à l'échelle, et n'engagera personne. Un audit, ça engage quelqu'un. » |
| **« Vous êtes seul »** | « Structure légère, méthode outillée. C'est ce qui me permet d'être indépendant — et de vous coûter moins qu'un grand cabinet pour un travail plus précis. » |

