# Stratégie commerciale rAIme

> **Objectif :** maximiser le revenu en vendant du **jugement** (former, auditer, arbitrer), avec un coût de production qui baisse à mesure que les agents montent en autonomie.

---

## 1. Le modèle économique — comment on gagne vraiment

| Source | Nature | Rôle économique |
|---|---|---|
| **Former** | Tarif journalier, finançable (CPF/RS6776, aides) | **Porte d'entrée** : friction basse, trésorerie rapide |
| **Auditer** | Forfait | **Création de valeur** : c'est là qu'on prouve |
| **Arbitrer** | Forfait par lot de propositions | **Panier élevé** : l'enjeu client se chiffre en dizaines de k€ |
| **Contrôle après déploiement** | Abonnement trimestriel | **Récurrence (MRR)** : le vrai actif financier |

**Les 4 leviers, dans l'ordre :**
1. **Panier moyen** — faire monter chaque client sur l'échelle Former → Auditer → Arbitrer.
2. **Récurrence** — transformer chaque mission en contrôle trimestriel. C'est ce qui rend la boîte valorisable.
3. **Volume** — les agents commerciaux démultiplient le haut de tunnel.
4. **Marge** — les agents de production font baisser le coût d'un audit ; à prix constant, la marge monte.

**Règle de tarification :** on facture **la valeur évitée**, jamais les heures. Un audit à 3 000 € qui évite 9 840 €/an de surcoût se vend seul. Le temps passé ne regarde que nous.

---

## 2. La cible (ICP)

**Profil :** PME / ETI de **20 à 250 salariés**, qui **ont reçu ou vont recevoir** une proposition d'automatisation ou d'IA.

**Le déclencheur d'achat — le seul qui compte :**
> « On nous a fait une proposition à 40 k€ et on est incapables de dire si c'est justifié. »

**Secteurs prioritaires :** services professionnels (cabinets comptables, avocats, conseil), industrie & logistique, santé/cliniques, immobilier & architecture, e-commerce.

**Interlocuteur :** dirigeant / DG en PME · DSI ou DAF en ETI. En PME, **toujours viser le dirigeant** : c'est lui qui signe, et c'est lui qui a un CPF.

**Signaux d'entrée :** recrutement « transformation digitale », appel d'offres en cours, annonce d'un projet IA, présence sur un salon IA, budget voté.

---

## 3. L'approche — le tunnel

```
   FORMATION (financée)        AUDIT              ARBITRAGE          CONTRÔLE
   friction basse        →  création de     →   panier élevé   →   récurrence
   trésorerie rapide        valeur prouvée      (le vrai gain)      (MRR)
```

**Le pivot commercial** se joue **pendant** la formation ou le diagnostic : c'est là qu'apparaît l'écart entre **ce qu'on leur vend** et **ce dont ils ont besoin**. On n'a pas à convaincre — on montre.

**Deux portes d'entrée :**
- **Porte A — Formation** (la plus facile) : « on forme vos équipes, c'est finançable ». Personne ne refuse d'en parler.
- **Porte B — Diagnostic flash** (30 min, offert) : on lit une proposition reçue et on pointe 3 angles morts. Redoutable quand ils ont un devis en main.

