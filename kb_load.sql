## 5. L'argumentaire — 5 arguments, 5 preuves

| Argument | La preuve à donner |
|---|---|
| **1. Vous ne pouvez pas vérifier vous-même** | Les 8 questions de challenge : posez-les à votre prestataire, observez la réponse |
| **2. Le plus puissant coûte souvent pour rien** | L'exemple des 30 000 e-mails : écart de qualité négligeable, écart de coût majeur |
| **3. Le coût explose en silence** | Le coût par exécution à volume ×10 — presque jamais chiffré dans un devis |
| **4. Vous risquez de vous enfermer** | La réversibilité : pouvez-vous partir avec vos données et vos workflows ? |
| **5. Nous sommes réellement indépendants** | Rémunération au forfait, **zéro commission fournisseur**, conflits déclarés |

**L'arme absolue :** ne pas argumenter — **poser les 8 questions**. Le prospect réalise seul qu'il ne sait pas y répondre.

